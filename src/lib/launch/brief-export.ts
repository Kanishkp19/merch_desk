import type { LaunchPlan } from './types'
import { STATUS_LABELS } from './types'
import { planEconomics } from './checklist'
import { formatPaise, SCENARIOS } from '@/lib/economics/engine'
import type { ScenarioName } from '@/lib/economics/schema'

const SCENARIO_LABEL: Record<ScenarioName, string> = {
  conservative: 'Conservative (60% of your sales guess)',
  base: 'Base (your sales guess)',
  optimistic: 'Optimistic (130%, capped by stock)',
}

/**
 * Exportable launch brief: the printable line sheet evolved into a launch
 * document — assortment, economics with assumptions, and every unresolved
 * item. Markdown so it can be pasted, printed or attached to the quote flow.
 */
export function launchBriefMarkdown(plan: LaunchPlan): string {
  const { result } = planEconomics(plan)
  const b = plan.brief
  const lines: string[] = []

  lines.push(`# Launch brief — ${plan.name}`)
  lines.push('')
  lines.push(`_Generated by MerchDesk on ${new Date(plan.updatedAt).toLocaleDateString('en-IN')}. Prices and costs are illustrative INR estimates until a supplier quote confirms them._`)
  lines.push('')

  lines.push('## The launch')
  lines.push(`- Creator: ${b.creatorName} — ${b.projectName}`)
  lines.push(`- Purpose: ${b.purpose}`)
  lines.push(`- Target date: ${b.targetDateUnknown ? 'Not fixed yet' : b.targetDate || 'Not given'}`)
  lines.push(`- City / delivery region: ${b.city}`)
  lines.push(`- Selling channel: ${b.sellingChannel.replace(/_/g, ' ')}`)
  lines.push(`- Fulfilment: ${b.fulfilment.replace(/_/g, ' ')}`)
  if (b.audienceEvidence) lines.push(`- Audience evidence (creator-stated): ${b.audienceEvidence}`)
  if (b.notes) lines.push(`- Notes: ${b.notes}`)
  lines.push('')

  lines.push('## Assortment')
  for (const l of plan.lines.filter((x) => x.included)) {
    lines.push(`### ${l.name} — ${l.quantityOrdered} units at ${formatPaise(l.sellPrice)}${plan.pricesIncludeGst ? ' incl. GST' : ' + GST'}`)
    lines.push(`- Why recommended: fit score ${l.fitScore} from ${l.evidence.length} evidence link${l.evidence.length === 1 ? '' : 's'} (${l.recommendationSource === 'rules' ? 'rules-based match to your audience tags' : l.recommendationSource === 'manual' ? 'manually added by you' : 'AI-assisted description, rules-based selection'})`)
    if (l.evidence.length > 0) {
      lines.push(`- Evidence: ${l.evidence.slice(0, 3).map((e) => e.label).join(', ')}`)
    }
    lines.push(`- Spec: ${l.supplierBrief}`)
    lines.push(`- Lead time: requires supplier confirmation (none verified)`)
    if (!l.unitCostKnown) lines.push(`- ⚠ Unit cost is an unconfirmed estimate — a written quote is required`)
    if (!l.artworkReady) lines.push(`- ⚠ Final artwork not ready`)
    if (l.complianceNote) lines.push(`- Compliance: ${l.complianceNote}`)
    lines.push('')
  }

  lines.push('## Economics')
  lines.push(`- Upfront cash (known costs): ${formatPaise(result.upfrontCash)}${result.upfrontCashComplete ? '' : ' + unconfirmed items listed below'}`)
  lines.push(`- GST treatment: prices ${plan.pricesIncludeGst ? 'include' : 'exclude'} GST; rates are indicative, confirm with a CA`)
  lines.push('')
  lines.push(`| Scenario | Units sold | Contribution | Final profit (batch) | Unsold units | Capital in unsold stock |`)
  lines.push(`| --- | --- | --- | --- | --- | --- |`)
  for (const s of SCENARIOS) {
    const p = result.perScenario[s]
    lines.push(`| ${SCENARIO_LABEL[s]} | ${p.unitsSold} | ${formatPaise(p.contribution)} | ${formatPaise(p.finalProfit)} | ${p.unsoldUnits} | ${formatPaise(p.capitalTiedInUnsold)} |`)
  }
  lines.push('')
  const base = result.perScenario.base
  lines.push(
    base.breakEvenUnits === null
      ? `- Break-even: ${base.breakEvenImpossibleReason ?? 'not computable'}`
      : `- Break-even: about ${base.breakEvenUnits} units across the batch, recovering fixed costs, the full inventory purchase and the defect allowance (${base.breakEvenReachableInBatch ? `reachable — the assumed mix can sell up to ${base.mixFeasibleUnits} units within the stock ordered` : `NOT reachable — the assumed mix can only sell ${base.mixFeasibleUnits} units within the stock ordered, so break-even needs more stock, a higher price or a different mix`}), based on the sales mix: ${result.salesMix.map((m) => `${m.name} ${(m.weight * 100).toFixed(0)}%`).join(', ')}`
  )
  lines.push('')

  lines.push('## What these numbers mean')
  for (const d of result.definitions) lines.push(`- **${d.metric}** — ${d.definition}`)
  lines.push('')

  if (result.unconfirmed.length > 0) {
    lines.push('## Unconfirmed items (nothing here is invented)')
    for (const u of result.unconfirmed) lines.push(`- [ ] ${u.item}: ${u.detail}`)
    lines.push('')
  }

  lines.push('## Checklist')
  for (const c of plan.checklist) {
    if (c.status === 'not_needed') continue
    lines.push(`- [${c.status === 'done' ? 'x' : ' '}] ${c.label}${c.date ? ` (target: ${c.date})` : ''} — ${c.hint}`)
  }
  lines.push('')

  if (plan.submission) {
    lines.push('## Quote request')
    lines.push(`- Reference: ${plan.submission.ref}`)
    lines.push(`- Submitted: ${new Date(plan.submission.submittedAt).toLocaleString('en-IN')}`)
    lines.push(`- Status: tracked separately — edits made after submission do not change the request the operator received.`)
    lines.push(
      '- Creator gates are three separate decisions: (1) quote acceptance, (2) sample approval, (3) production authorization. Each is recorded individually; none implies another, and none implies supplier acceptance, payment or a delivery guarantee.'
    )
  }

  return lines.join('\n')
}

export function statusLabel(status: string): string {
  return STATUS_LABELS[status as keyof typeof STATUS_LABELS] ?? status
}
